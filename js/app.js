      if (m === 'junction') h = '點兩條路段 (路段中心線) 的交會處 — 自動產生路口範圍、行人穿越道與停止線';
      if (m === 'point') h = '點擊放置 — 自動對齊最近車道的行車方向；<kbd>[ ]</kbd> 旋轉，<kbd>F</kbd> 反轉';
